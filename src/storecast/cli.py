"""End-to-end demo: generate data, backtest, simulate, write metrics and charts.

python -m storecast            # full run, about 4 minutes on a laptop
python -m storecast --quick    # small run for CI, under a minute
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

from . import plots, simulate
from .backtest import rolling_forecasts, summarize
from .features import build_features
from .model import QuantileForecaster
from .synth import SynthConfig, generate

TEST_WEEKS = 26


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] + ["---:"] * (len(headers) - 1)) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> dict:
    ap = argparse.ArgumentParser(
        prog="storecast", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--out", type=Path, default=Path("results"), help="where metrics go")
    ap.add_argument("--img", type=Path, default=Path("docs/img"), help="where charts go")
    ap.add_argument("--quick", action="store_true", help="small dataset and model, for CI")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    args.img.mkdir(parents=True, exist_ok=True)
    t0 = time.time()

    def log(msg: str) -> None:
        print(f"[{time.time() - t0:6.1f}s] {msg}", flush=True)

    if args.quick:
        cfg = SynthConfig(n_stores=3, n_skus=12, n_weeks=110, seed=args.seed)
        n_test, grid = 8, {p: ks[::2] for p, ks in simulate.FRONTIER_GRID.items()}

        def make_model() -> QuantileForecaster:
            m = QuantileForecaster()
            m.params["n_estimators"] = 60
            return m
    else:
        cfg = SynthConfig(seed=args.seed)
        n_test, grid, make_model = TEST_WEEKS, simulate.FRONTIER_GRID, QuantileForecaster

    data = generate(cfg)
    log(f"generated {len(data.sales):,} rows: {cfg.n_stores} stores x {cfg.n_skus} SKUs x {cfg.n_weeks} weeks")
    rows = build_features(data.sales)
    log(f"built {len(rows):,} feature rows")

    last = cfg.n_weeks - 1
    origins = range(last - 4 - n_test + 1, last - 4 + 1)  # each origin has 4 weeks of actuals after it
    fc = rolling_forecasts(rows, origins, make_model=make_model, log=log)
    bt = summarize(fc)
    log(f"backtest WAPE: model {bt['methods']['lgbm_p50']['wape']:.3f}, 8-week avg {bt['methods']['ma8']['wape']:.3f}")

    totals, traces = simulate.run(data.sales, fc, data.catalog)
    sim = simulate.summarize(totals)
    log("simulated default policies")
    front = simulate.frontier(data.sales, fc, data.catalog, grid=grid)
    log(f"swept {len(front)} policy settings")

    base_inv = sim["minmax"]["avg_inventory_value"]
    at_equal = {p: simulate.lost_share_at(front, p, base_inv) for p in simulate.POLICIES}
    best = front.loc[front.groupby("policy")["total_cost"].idxmin()].set_index("policy")
    frontier_summary = {
        "lost_share_at_minmax_inventory": at_equal,
        "best_total_cost": {p: float(best.loc[p, "total_cost"]) for p in simulate.POLICIES},
        "best_knob": {p: float(best.loc[p, "knob"]) for p in simulate.POLICIES},
        "best_cost_vs_best_minmax": float(
            best.loc["ddmrp_forecast", "total_cost"] / best.loc["minmax", "total_cost"] - 1
        ),
        # If a policy's best setting sits on the edge of the grid, widen the grid before trusting the comparison.
        "best_is_interior": {
            p: bool(best.loc[p, "knob"] not in (min(grid[p]), max(grid[p]))) for p in simulate.POLICIES
        },
    }

    metrics = {
        "config": {**cfg.__dict__, "test_weeks": n_test, "quick": args.quick},
        "backtest": bt,
        "simulation_default": sim,
        "frontier": frontier_summary,
    }
    (args.out / "metrics.json").write_text(json.dumps(metrics, indent=2))
    front.to_csv(args.out / "frontier.csv", index=False, float_format="%.5f")

    m = bt["methods"]
    md = [
        "# Results (synthetic data)",
        "",
        f"Generated by `python -m storecast{' --quick' if args.quick else ''}`.",
        "",
    ]
    md += ["## Forecast accuracy", ""]
    md.append(
        _table(
            ["Method", "WAPE", "Bias"],
            [[m[k]["label"], f"{m[k]['wape']:.1%}", f"{m[k]['bias']:+.1%}"] for k in ("lgbm_p50", "ma8", "snaive")],
        )
    )
    md += ["", f"p10 to p90 interval coverage: {bt['interval_coverage_p10_p90']:.1%} (target 80%).", ""]
    md += ["## Reorder policies, default settings", ""]
    md.append(
        _table(
            ["Policy", "Fill rate", "Lost units", "Avg inventory value", "Holding cost", "Lost margin", "Total cost"],
            [
                [
                    s["label"],
                    f"{s['fill_rate']:.1%}",
                    f"{s['lost_units']:,}",
                    f"${s['avg_inventory_value']:,.0f}",
                    f"${s['holding_cost']:,.0f}",
                    f"${s['lost_margin']:,.0f}",
                    f"${s['total_cost']:,.0f}",
                ]
                for s in sim.values()
            ],
        )
    )
    md += ["", "## Same inventory, different policy", ""]
    md.append(
        _table(
            ["Policy", f"Lost sales at ${base_inv:,.0f} inventory", "Best total cost (tuned)"],
            [
                [simulate.POLICIES[p], f"{at_equal[p]:.1%}", f"${frontier_summary['best_total_cost'][p]:,.0f}"]
                for p in simulate.POLICIES
            ],
        )
    )
    (args.out / "summary.md").write_text("\n".join(md) + "\n")

    store, sku = plots.pick_series(fc)
    plots.forecast_fan(data.sales, fc, store, sku, args.img / "forecast-fan.png")
    plots.wape_bars(bt, args.img / "backtest-wape.png")
    plots.frontier_chart(front, simulate.POLICIES, simulate.DEFAULT_KNOBS, args.img / "policy-frontier.png")
    plots.buffer_trace(traces, store, sku, args.img / "buffer-zones.png")
    log(f"wrote {args.out}/metrics.json, {args.out}/summary.md and 4 charts in {args.img}/")
    return metrics


if __name__ == "__main__":
    main()
